package com.uranus.lms;

import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.boot.context.event.ApplicationReadyEvent;
import org.springframework.context.event.EventListener;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;

@Component
@RequiredArgsConstructor
@Slf4j
public class DatabaseConstraintFixer {

    private final JdbcTemplate jdbcTemplate;

    @EventListener(ApplicationReadyEvent.class)
    public void onApplicationReady() {
        log.info("Checking and forcefully dropping problematic database constraints...");
        try {
            // Force drop the known bad constraints generated by Hibernate
            jdbcTemplate.execute("ALTER TABLE student_answers DROP CONSTRAINT IF EXISTS fk8dhrgyyw99oyj0q650s1x2xo3");
            jdbcTemplate.execute("ALTER TABLE student_exam_results DROP CONSTRAINT IF EXISTS fksqsdqb9r24js1ylry8bg78ybu");
            jdbcTemplate.execute("ALTER TABLE deck_ratings DROP CONSTRAINT IF EXISTS fk9v9lj1y7xtl13hyc9fjd53c2e");
            
            // Just to be absolutely safe, let's also remove any other weird hash constraints that might have been recreated.
            jdbcTemplate.execute("""
                DO $$
                DECLARE
                    fk text;
                    r RECORD;
                    col_name text;
                BEGIN
                    FOR fk IN (SELECT conname FROM pg_constraint WHERE conrelid = 'student_answers'::regclass AND confrelid = 'questions'::regclass AND contype = 'f' AND conname NOT LIKE 'fk_student_answers_%') LOOP
                        EXECUTE 'ALTER TABLE student_answers DROP CONSTRAINT IF EXISTS ' || fk;
                    END LOOP;
                    
                    FOR fk IN (SELECT conname FROM pg_constraint WHERE conrelid = 'student_answers'::regclass AND confrelid = 'student_exam_results'::regclass AND contype = 'f' AND conname NOT LIKE 'fk_student_answers_%') LOOP
                        EXECUTE 'ALTER TABLE student_answers DROP CONSTRAINT IF EXISTS ' || fk;
                    END LOOP;
                    
                    -- Flashcard constraints
                    FOR fk IN (SELECT conname FROM pg_constraint WHERE conrelid = 'deck_ratings'::regclass AND confrelid = 'flashcard_decks'::regclass AND contype = 'f' AND conname NOT LIKE 'fk_deck_ratings_%') LOOP
                        EXECUTE 'ALTER TABLE deck_ratings DROP CONSTRAINT IF EXISTS ' || fk;
                    END LOOP;
                    
                    FOR fk IN (SELECT conname FROM pg_constraint WHERE conrelid = 'student_favorite_decks'::regclass AND confrelid = 'flashcard_decks'::regclass AND contype = 'f' AND conname NOT LIKE 'fk_student_favorite_decks_%') LOOP
                        EXECUTE 'ALTER TABLE student_favorite_decks DROP CONSTRAINT IF EXISTS ' || fk;
                    END LOOP;
                    
                    FOR fk IN (SELECT conname FROM pg_constraint WHERE conrelid = 'flashcards'::regclass AND confrelid = 'flashcard_decks'::regclass AND contype = 'f' AND conname NOT LIKE 'fk_flashcards_%') LOOP
                        EXECUTE 'ALTER TABLE flashcards DROP CONSTRAINT IF EXISTS ' || fk;
                    END LOOP;
                    
                    -- Folder constraints
                    FOR fk IN (SELECT conname FROM pg_constraint WHERE conrelid = 'exams'::regclass AND confrelid = 'content_folders'::regclass AND contype = 'f' AND conname NOT LIKE 'fk_exams_%') LOOP
                        EXECUTE 'ALTER TABLE exams DROP CONSTRAINT IF EXISTS ' || fk;
                    END LOOP;
                    
                    FOR fk IN (SELECT conname FROM pg_constraint WHERE conrelid = 'flashcard_decks'::regclass AND confrelid = 'content_folders'::regclass AND contype = 'f' AND conname NOT LIKE 'fk_flashcard_decks_%') LOOP
                        EXECUTE 'ALTER TABLE flashcard_decks DROP CONSTRAINT IF EXISTS ' || fk;
                    END LOOP;

                    -- Cascade delete enforcement
                    FOR r IN
                        SELECT 
                            c.conname AS constraint_name,
                            c.conrelid::regclass::text AS table_name,
                            c.confrelid::regclass::text AS referenced_table
                        FROM pg_constraint c
                        WHERE c.confrelid IN (
                            'users'::regclass, 'flashcards'::regclass, 'flashcard_decks'::regclass, 
                            'exams'::regclass, 'questions'::regclass, 'content_folders'::regclass,
                            'assignments'::regclass, 'classrooms'::regclass, 'courses'::regclass,
                            'lessons'::regclass, 'class_posts'::regclass, 'class_post_comments'::regclass,
                            'sections'::regclass, 'discussions'::regclass
                        )
                          AND c.contype = 'f'
                          AND c.confdeltype != 'c'
                    LOOP
                        SELECT a.attname INTO col_name
                        FROM pg_attribute a
                        JOIN pg_constraint c2 ON c2.conname = r.constraint_name
                        WHERE a.attnum = ANY(c2.conkey) AND a.attrelid = c2.conrelid;
                        
                        EXECUTE 'ALTER TABLE ' || r.table_name || ' DROP CONSTRAINT ' || r.constraint_name;
                        EXECUTE 'ALTER TABLE ' || r.table_name || ' ADD CONSTRAINT ' || r.constraint_name || ' FOREIGN KEY (' || col_name || ') REFERENCES ' || r.referenced_table || '(id) ON DELETE CASCADE';
                    END LOOP;
                END $$;
            """);

            log.info("Forcefully dropped problematic constraints successfully.");
        } catch (Exception e) {
            log.warn("Failed to drop constraints on startup: {}", e.getMessage());
        }
    }
}
